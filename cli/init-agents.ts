function mergeAgentsMd(baseContent: string): string {
  const structure = parseAgentsMd(baseContent);
  const kickstartSection = genDnSection();
  let result = baseContent;

  if (structure.hasCursorRules) {
    const cursorSection = structure.sections.find((s) =>
      s.name.includes("Cursor") || s.name.includes("Copilot")
    );
    if (cursorSection) {
      const sectionContent = cursorSection.content.toLowerCase();
      if (!sectionContent.includes("kickstart")) {
        const lines = result.split("\n");
        const sectionEndLine = cursorSection.endLine;
        let insertLine = sectionEndLine;
        for (let i = cursorSection.startLine; i <= sectionEndLine; i++) {
          if (lines[i].trim() === "" && i > cursorSection.startLine + 2) {
            insertLine = i;
            break;
          }
        }
        const beforeRule = lines.slice(0, insertLine).join("\n");
        const afterRule = lines.slice(insertLine).join("\n");
        const kickstartRule =
          "- If \`.cursor/rules/kickstart.mdc\` exists, follow kickstart subagent guidelines.";
        result = beforeRule + "\n" + kickstartRule + "\n" + afterRule;
      }
    }
  }

  if (hasDnSection(result)) {
    return result;
  }

  const updatedStructure = parseAgentsMd(result);
  let insertIndex = -1;

  const preferredInsertAfter = [
    "Agent Expectations",
    "Cursor",
    "Copilot",
    "Git",
    "Testing Guidelines",
  ];

  for (let i = updatedStructure.sections.length - 1; i >= 0; i--) {
    const section = updatedStructure.sections[i];
    if (
      preferredInsertAfter.some((name) => section.name.includes(name))
    ) {
      insertIndex = section.endLine + 1;
      break;
    }
  }

  if (insertIndex === -1 && updatedStructure.customSections.length > 0) {
    const firstCustomIndex = updatedStructure.sections.findIndex((s) =>
      updatedStructure.customSections.includes(s.name)
    );
    if (firstCustomIndex !== -1) {
      insertIndex = updatedStructure.sections[firstCustomIndex].startLine;
    }
  }

  if (insertIndex === -1) {
    const lines = result.split("\n");
    while (lines.length > 0 && lines[lines.length - 1].trim() === "") {
      lines.pop();
    }
    return lines.join("\n") + "\n\n" + kickstartSection;
  }

  const lines = result.split("\n");
  const before = lines.slice(0, insertIndex).join("\n");
  const after = lines.slice(insertIndex).join("\n");

  const spacing = after.trim().startsWith("#") ? "\n\n" : "\n";
  return before + spacing + kickstartSection + spacing + after;
}

function isMinimalAgentsMd(content: string): boolean {
  const trimmed = content.trim();
  if (trimmed.length < 500) {
    return true;
  }

  const structure = parseAgentsMd(content);
  if (structure.sections.length < 3) {
    return true;
  }

  if (!structure.hasProjectOverview && !structure.hasBuildLintTest) {
    return true;
  }

  return false;
}

function generateMinimalTemplate(): string {
  return `# AGENTS.md

This file provides instructions for agentic coding agents operating in this repository.

${genDnSection()}`;
}

function isSkillAgent(value: string): value is SkillAgent {
  return SUPPORTED_SKILL_AGENTS.some((agent) => agent === value);
}

function fail(message: string): never {
  console.error(message);
  Deno.exit(1);
}

function parseInitAgentsOptions(args: string[]): InitAgentsOptions {
  const options: InitAgentsOptions = {
    skill: false,
    scope: "repo",
    dryRun: false,
    json: false,
    force: false,
  };

  for (let index = 0; index < args.length; index++) {
    const arg = args[index];

    if (arg === "--skill") {
      options.skill = true;
    } else if (arg === "--agent") {
      const value = args[index + 1];
      if (!value || value.startsWith("-")) {
        fail("--agent requires one of: codex, claude, opencode, cursor");
      }
      if (!isSkillAgent(value)) {
        fail(`Unsupported agent for --skill: ${value}`);
      }
      options.agent = value;
      index++;
    } else if (arg === "--scope") {
      const value = args[index + 1];
      if (value !== "repo" && value !== "user") {
        fail("--scope requires one of: repo, user");
      }
      options.scope = value;
      index++;
    } else if (arg === "--dry-run") {
      options.dryRun = true;
    } else if (arg === "--json") {
      options.json = true;
    } else if (arg === "--force") {
      options.force = true;
    }
  }

  return options;
}

function getHomeDirectory(): string {
  const home = Deno.env.get("DN_INIT_AGENTS_HOME") ?? Deno.env.get("HOME") ??
    Deno.env.get("USERPROFILE");
  if (!home) {
    fail("Unable to resolve home directory for --scope user");
  }
  return home;
}

function skillBaseDirectory(
  workspaceRoot: string,
  agent: SkillAgent,
  scope: SkillScope,
): string {
  if (scope === "repo") {
    if (agent === "claude") {
      return join(workspaceRoot, ".claude", "skills", "dn");
    }
    if (agent === "cursor") {
      return join(workspaceRoot, ".cursor", "rules");
    }
    return join(workspaceRoot, ".agents", "skills", "dn");
  }

  const home = getHomeDirectory();
  if (agent === "claude") {
    return join(home, ".claude", "skills", "dn");
  }
  return join(home, ".agents", "skills", "dn");
}

function buildSkillTargets(
  workspaceRoot: string,
  agent: SkillAgent,
  scope: SkillScope,
): SkillTarget[] {
  if (scope === "user" && agent === "cursor") {
    fail(
      "Cursor skill installation is repo-scoped. Use: dn init agents --skill --agent cursor --scope repo",
    );
  }

  const baseDirectory = skillBaseDirectory(workspaceRoot, agent, scope);

  if (agent === "cursor") {
    return [{
      path: join(baseDirectory, "dn.mdc"),
      content: CURSOR_RULE_CONTENT,
    }];
  }

  const targets: SkillTarget[] = [{
    path: join(baseDirectory, "SKILL.md"),
    content: DN_SKILL_CONTENT,
  }];

  if (agent === "codex" || agent === "opencode") {
    targets.push({
      path: join(baseDirectory, "agents", "openai.yaml"),
      content: OPENAI_METADATA_CONTENT,
    });
  }

  return targets;
}

async function fileExists(path: string): Promise<boolean> {
  try {
    const stat = await Deno.stat(path);
    return stat.isFile;
  } catch {
    return false;
  }
}

async function planSkillTarget(target: SkillTarget): Promise<InstallResult> {
  if (!await fileExists(target.path)) {
    return {
      path: target.path,
      status: "write",
      reason: "missing",
    };
  }

  const existingContent = await Deno.readTextFile(target.path);
  if (existingContent === target.content) {
    return {
      path: target.path,
      status: "skip",
      reason: "current",
    };
  }

  if (existingContent.includes(GENERATED_MARKER)) {
    return {
      path: target.path,
      status: "write",
      reason: "managed-outdated",
    };
  }

  return {
    path: target.path,
    status: "conflict",
    reason: "existing-unmanaged-file",
  };
}

async function installSkillTargets(
  targets: SkillTarget[],
  options: InitAgentsOptions,
): Promise<InstallResult[]> {
  const plannedResults = await Promise.all(targets.map(planSkillTarget));
  const conflicts = plannedResults.filter((result) =>
    result.status === "conflict"
  );

  if (conflicts.length > 0 && !options.force && !options.dryRun) {
    const files = conflicts.map((result) => `  - ${result.path}`).join("\n");
    fail(
      `Refusing to overwrite unmanaged skill file(s). Re-run with --force to replace them.\n${files}`,
    );
  }

  if (options.dryRun) {
    return plannedResults;
  }

  const results: InstallResult[] = [];
  for (const target of targets) {
    const plannedResult = plannedResults.find((result) =>
      result.path === target.path
    );
    if (!plannedResult) {
      throw new Error(`Missing planned result for ${target.path}`);
    }

    if (plannedResult.status === "skip") {
      results.push(plannedResult);
      continue;
    }

    await Deno.mkdir(dirname(target.path), { recursive: true });
    await Deno.writeTextFile(target.path, target.content);
    results.push({
      path: target.path,
      status: "write",
      reason: plannedResult.status === "conflict"
        ? "forced"
        : plannedResult.reason,
    });
  }

  return results;
}

function printSkillInstallResults(
  results: InstallResult[],
  options: InitAgentsOptions,
): void {
  if (options.json) {
    console.log(JSON.stringify({ results }, null, 2));
    return;
  }

  for (const result of results) {
    const prefix = options.dryRun ? "Would" : "Did";
    if (result.status === "write") {
      console.log(`${prefix} write ${result.path}`);
    } else if (result.status === "skip") {
      console.log(`Skipped ${result.path} (already current)`);
    } else {
      console.log(`Conflict ${result.path} (${result.reason})`);
    }
  }
}

async function handleInitAgentsSkill(
  workspaceRoot: string,
  options: InitAgentsOptions,
): Promise<void> {
  if (!options.agent) {
    fail(
      "dn init agents --skill requires --agent <codex|claude|opencode|cursor>\n\nExamples:\n  dn init agents --skill --agent codex\n  dn init agents --skill --agent claude\n  dn init agents --skill --agent opencode\n  dn init agents --skill --agent cursor",
    );
  }

  const targets = buildSkillTargets(
    workspaceRoot,
    options.agent,
    options.scope,
  );
  const results = await installSkillTargets(targets, options);
  printSkillInstallResults(results, options);
}

export async function handleInitAgents(args: string[]): Promise<void> {
  const workspaceRoot = Deno.cwd();

  const showHelp = args.includes("--help") || args.includes("-h");

  if (showHelp) {
    console.log(
      "dn init agents - Update AGENTS.md or install dn agent skill\n",
    );
    console.log("Usage:");
    console.log("  dn init agents\n");
    console.log("  dn init agents --skill --agent <agent> [options]\n");
    console.log("Description:");
    console.log(
      "  Updates the AGENTS.md file in the current directory with instructions",
    );
    console.log(
      "  for using dn CLI. If AGENTS.md doesn't exist, creates it.",
    );
    console.log(
      "  With --skill, installs native dn skill files for one selected agent.\n",
    );
    console.log("Options:");
    console.log("  --skill                 Install native skill files");
    console.log(
      "  --agent <agent>         Required with --skill: codex, claude, opencode, cursor",
    );
    console.log("  --scope <repo|user>     Install scope (default: repo)");
    console.log("  --dry-run               Report changes without writing");
    console.log("  --json                  Emit JSON output for --skill");
    console.log(
      "  --force                 Replace conflicting unmanaged files",
    );
    console.log("  --help, -h              Show this help message\n");
    console.log("Examples:");
    console.log("  dn init agents");
    console.log("  dn init agents --skill --agent codex");
    console.log("  dn init agents --skill --agent claude --dry-run --json");
    Deno.exit(0);
  }

  const options = parseInitAgentsOptions(args);

  if (options.skill) {
    await handleInitAgentsSkill(workspaceRoot, options);
    return;
  }

  const agentsMdPath = join(workspaceRoot, "AGENTS.md");

  let existingContent: string | undefined;
  let wasNewFile = false;

  try {
    existingContent = await Deno.readTextFile(agentsMdPath);
  } catch {
    wasNewFile = true;
  }

  let newContent: string;

  if (!existingContent || isMinimalAgentsMd(existingContent)) {
    newContent = generateMinimalTemplate();
  } else {
    newContent = mergeAgentsMd(existingContent);
  }

  await Deno.writeTextFile(agentsMdPath, newContent);

  if (wasNewFile) {
    console.log(`Created ${agentsMdPath} with dn instructions`);
  } else {
    console.log(`Updated ${agentsMdPath} with dn instructions`);
  }
}
