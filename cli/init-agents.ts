import { dirname, join } from "@std/path";

type SkillAgent = "codex" | "claude" | "opencode" | "cursor";
type SkillScope = "repo" | "user";
type InstallStatus = "write" | "skip" | "conflict";

interface InitAgentsOptions {
  skill: boolean;
  agent?: SkillAgent;
  scope: SkillScope;
  dryRun: boolean;
  json: boolean;
  force: boolean;
}

interface SkillTarget {
  path: string;
  content: string;
}

interface InstallResult {
  path: string;
  status: InstallStatus;
  reason: string;
}

